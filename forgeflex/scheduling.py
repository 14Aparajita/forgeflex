"""Tariff-aware production scheduling simulation for ForgeFlex.

This module compares an earliest-start baseline with a greedy cost-aware
non-preemptive schedule. Both use identical per-machine earliest-due-date
ordering to isolate the effect of tariff-aware placement. Inputs generated by this module are
synthetic. Results are simulation outputs, not measured factory savings.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

JOB_COLUMNS = {"job_id", "machine", "duration_slots", "power_kw", "release_slot", "due_slot"}
TARIFF_COLUMNS = {"slot", "price_per_kwh"}


def _default_tariff(horizon_slots: int) -> pd.DataFrame:
    """Explicit illustrative tariff in currency/kWh; not a real utility tariff."""
    prices = []
    for slot in range(horizon_slots):
        hour = slot % 24
        if 0 <= hour <= 5:
            price = 5.0
        elif 6 <= hour <= 9:
            price = 7.0
        elif 10 <= hour <= 17:
            price = 12.0
        elif 18 <= hour <= 20:
            price = 8.0
        else:
            price = 4.0
        prices.append({"slot": slot, "price_per_kwh": price})
    return pd.DataFrame(prices)


def _generate_demo_jobs(seed: int, job_count: int, horizon_slots: int) -> pd.DataFrame:
    if job_count < 1:
        raise ValueError("job_count must be >= 1.")
    if horizon_slots < 8:
        raise ValueError("horizon_slots must be >= 8 for the demo scenario.")
    rng = np.random.default_rng(seed)
    machines = ["SolderingOven", "VacuumPump1", "VacuumPump2", "PickAndPlaceUnit", "ChipSaw"]
    jobs = []
    for i in range(job_count):
        machine = machines[i % len(machines)]
        duration = int(rng.integers(1, min(4, max(2, horizon_slots // 4)) + 1))
        # Releases are intentionally in daytime slots so tariff-aware deferral can be demonstrated.
        release_max = max(1, min(12, horizon_slots - duration - 1))
        release = int(rng.integers(6 if horizon_slots >= 24 else 1, release_max + 1))
        due_min = min(horizon_slots, release + duration + 2)
        due_max = min(horizon_slots, max(due_min, release + duration + 10))
        due = int(rng.integers(due_min, due_max + 1)) if due_max > due_min else due_min
        power = float(np.round(rng.uniform(0.4, 5.0), 2))
        quantity = int(rng.integers(10, 101))
        jobs.append({
            "job_id": f"JOB-{i + 1:03d}",
            "machine": machine,
            "duration_slots": duration,
            "power_kw": power,
            "release_slot": release,
            "due_slot": due,
            "quantity_units": quantity,
        })
    return pd.DataFrame(jobs)


def _load_jobs(jobs_csv: str | Path | None, seed: int, job_count: int, horizon_slots: int) -> tuple[pd.DataFrame, str]:
    if jobs_csv:
        path = Path(jobs_csv)
        if not path.exists():
            raise FileNotFoundError(f"Jobs CSV not found: {path}")
        jobs = pd.read_csv(path)
        source = "USER_SUPPLIED_SCENARIO_INPUT"
    else:
        jobs = _generate_demo_jobs(seed, job_count, horizon_slots)
        source = "SYNTHETIC_DEMO_INPUT"
    missing = sorted(JOB_COLUMNS - set(jobs.columns))
    if missing:
        raise ValueError("Jobs CSV missing required columns: " + ", ".join(missing))
    if "quantity_units" not in jobs:
        jobs["quantity_units"] = 1
    jobs = jobs.copy()
    if jobs.empty:
        raise ValueError("Jobs input must contain at least one job.")
    if jobs["job_id"].isna().any() or jobs["job_id"].astype(str).duplicated().any():
        raise ValueError("job_id values must be non-empty and unique.")
    if jobs["machine"].isna().any() or (jobs["machine"].astype(str).str.strip() == "").any():
        raise ValueError("machine values must be non-empty.")
    for col in ("duration_slots", "power_kw", "release_slot", "due_slot", "quantity_units"):
        jobs[col] = pd.to_numeric(jobs[col], errors="coerce")
        if jobs[col].isna().any() or not np.isfinite(jobs[col].to_numpy(dtype=float)).all():
            raise ValueError(f"{col} must contain finite numeric values.")
    for col in ("duration_slots", "release_slot", "due_slot", "quantity_units"):
        if (jobs[col] % 1 != 0).any():
            raise ValueError(f"{col} must contain integer values.")
        jobs[col] = jobs[col].astype(int)
    if (jobs["duration_slots"] < 1).any():
        raise ValueError("duration_slots must be >= 1.")
    if (jobs["power_kw"] < 0).any():
        raise ValueError("power_kw must be >= 0.")
    if (jobs["quantity_units"] < 0).any():
        raise ValueError("quantity_units must be >= 0.")
    if (jobs["release_slot"] < 0).any() or (jobs["due_slot"] > horizon_slots).any():
        raise ValueError("release_slot must be >= 0 and due_slot must not exceed horizon_slots.")
    if (jobs["due_slot"] <= jobs["release_slot"]).any():
        raise ValueError("Each due_slot must be later than its release_slot.")
    if (jobs["release_slot"] + jobs["duration_slots"] > horizon_slots).any():
        raise ValueError("At least one job cannot fit in the horizon after its release.")
    return jobs, source


def _load_tariff(tariff_csv: str | Path | None, horizon_slots: int) -> tuple[pd.DataFrame, str]:
    if tariff_csv:
        path = Path(tariff_csv)
        if not path.exists():
            raise FileNotFoundError(f"Tariff CSV not found: {path}")
        tariff = pd.read_csv(path)
        source = "USER_SUPPLIED_SCENARIO_INPUT"
        missing = sorted(TARIFF_COLUMNS - set(tariff.columns))
        if missing:
            raise ValueError("Tariff CSV missing required columns: " + ", ".join(missing))
        tariff = tariff[["slot", "price_per_kwh"]].copy()
        tariff["slot"] = pd.to_numeric(tariff["slot"], errors="coerce")
        tariff["price_per_kwh"] = pd.to_numeric(tariff["price_per_kwh"], errors="coerce")
        if tariff.isna().any().any() or not np.isfinite(tariff.to_numpy(dtype=float)).all():
            raise ValueError("Tariff values must be finite numbers.")
        if (tariff["slot"] % 1 != 0).any():
            raise ValueError("Tariff slot values must be integers.")
        tariff["slot"] = tariff["slot"].astype(int)
        if tariff["slot"].duplicated().any():
            raise ValueError("Tariff must contain at most one price per slot.")
        if set(tariff["slot"]) != set(range(horizon_slots)):
            raise ValueError(f"Tariff must contain exactly slots 0 through {horizon_slots - 1}.")
        if (tariff["price_per_kwh"] < 0).any():
            raise ValueError("price_per_kwh must be >= 0.")
        tariff = tariff.sort_values("slot").reset_index(drop=True)
    else:
        tariff = _default_tariff(horizon_slots)
        source = "SYNTHETIC_ILLUSTRATIVE_TARIFF"
    return tariff, source


def _find_free_start(occupied: np.ndarray, release: int, duration: int, latest_start: int) -> list[int]:
    starts = []
    for start in range(release, latest_start + 1):
        if not occupied[start:start + duration].any():
            starts.append(start)
    return starts


def _schedule(jobs: pd.DataFrame, tariff: pd.DataFrame, horizon_slots: int, mode: str) -> pd.DataFrame:
    price = tariff.set_index("slot")["price_per_kwh"].to_dict()
    all_rows: list[dict[str, Any]] = []
    for machine, group in jobs.groupby("machine", sort=True):
        occupied = np.zeros(horizon_slots, dtype=bool)
        if mode not in {"baseline", "optimized"}:
            raise ValueError(f"Unknown scheduling mode: {mode}")
        # Use identical EDD ordering in both scenarios so the comparison
        # isolates earliest-start versus tariff-aware placement.
        ordered = group.sort_values(["due_slot", "release_slot", "job_id"], kind="stable")
        for _, job in ordered.iterrows():
            duration = int(job.duration_slots)
            release = int(job.release_slot)
            due = int(job.due_slot)
            last_horizon_start = horizon_slots - duration
            starts = _find_free_start(occupied, release, duration, min(due - duration, last_horizon_start))
            deadline_feasible_exists = bool(starts)
            if not starts:
                starts = _find_free_start(occupied, release, duration, last_horizon_start)
            if not starts:
                all_rows.append({**job.to_dict(), "schedule_mode": mode, "scheduled": False,
                                 "start_slot": None, "completion_slot": None, "deadline_met": False,
                                 "energy_kwh": 0.0, "energy_cost": 0.0,
                                 "schedule_note": "No contiguous machine time available in horizon."})
                continue
            if mode == "baseline":
                start = starts[0]
            else:
                # Greedy look-ahead over each feasible contiguous start; minimum cost, then earliest start.
                def block_cost(s: int) -> float:
                    return float(job.power_kw) * float(np.sum([price[k] for k in range(s, s + duration)]))
                start = min(starts, key=lambda s: (block_cost(s), s))
            completion = start + duration
            occupied[start:completion] = True
            slot_hours = 1.0  # overwritten by caller in energy conversion below
            all_rows.append({
                **job.to_dict(),
                "schedule_mode": mode,
                "scheduled": True,
                "start_slot": int(start),
                "completion_slot": int(completion),
                "deadline_met": bool(completion <= due),
                "deadline_feasible_at_placement": bool(deadline_feasible_exists),
                "energy_kwh": float(job.power_kw) * duration,
                "energy_cost": float(job.power_kw) * float(np.sum([price[k] for k in range(start, completion)])),
                "schedule_note": "scheduled" if completion <= due else "deadline_missed",
            })
    return pd.DataFrame(all_rows)


def _profile(schedule: pd.DataFrame, tariff: pd.DataFrame, horizon_slots: int, slot_hours: float) -> pd.DataFrame:
    prices = tariff.set_index("slot")["price_per_kwh"].to_dict()
    load = np.zeros(horizon_slots, dtype=float)
    if not schedule.empty:
        for _, row in schedule.iterrows():
            if not bool(row["scheduled"]):
                continue
            start, end = int(row["start_slot"]), int(row["completion_slot"])
            load[start:end] += float(row["power_kw"])
    return pd.DataFrame({
        "slot": np.arange(horizon_slots, dtype=int),
        "price_per_kwh": [float(prices[i]) for i in range(horizon_slots)],
        "aggregate_scheduled_load_kw": load,
        "slot_energy_kwh": load * slot_hours,
        "slot_energy_cost": load * slot_hours * np.array([prices[i] for i in range(horizon_slots)]),
    })


def _summary(schedule: pd.DataFrame, profile: pd.DataFrame, horizon_slots: int, slot_hours: float) -> dict[str, Any]:
    scheduled = schedule[schedule["scheduled"] == True] if not schedule.empty else schedule
    total_jobs = int(len(schedule))
    scheduled_jobs = int(len(scheduled))
    energy = float(profile["slot_energy_kwh"].sum())
    cost = float(profile["slot_energy_cost"].sum())
    misses = int((~scheduled["deadline_met"].astype(bool)).sum()) if scheduled_jobs else 0
    return {
        "jobs_requested": total_jobs,
        "jobs_scheduled": scheduled_jobs,
        "jobs_unscheduled": total_jobs - scheduled_jobs,
        "deadline_misses_among_scheduled_jobs": misses,
        "deadline_met_fraction_of_scheduled_jobs": float((scheduled["deadline_met"].astype(bool).mean())) if scheduled_jobs else None,
        "total_energy_kwh": energy,
        "total_energy_cost": cost,
        "peak_aggregate_demand_kw": float(profile["aggregate_scheduled_load_kw"].max()) if len(profile) else 0.0,
        "total_production_units_scheduled": float(scheduled["quantity_units"].sum()) if scheduled_jobs and "quantity_units" in scheduled else 0.0,
        "horizon_slots": int(horizon_slots),
        "slot_hours": float(slot_hours),
    }


def run_scheduling_simulation(
    output_dir: str | Path,
    jobs_csv: str | Path | None = None,
    tariff_csv: str | Path | None = None,
    seed: int = 42,
    job_count: int = 20,
    horizon_slots: int = 24,
    slot_hours: float = 1.0,
) -> dict[str, Any]:
    """Compare FCFS earliest-start scheduling with tariff-aware greedy scheduling."""
    if horizon_slots < 1:
        raise ValueError("horizon_slots must be >= 1.")
    if not np.isfinite(slot_hours) or slot_hours <= 0:
        raise ValueError("slot_hours must be a finite positive number.")
    jobs, jobs_source = _load_jobs(jobs_csv, seed, job_count, horizon_slots)
    tariff, tariff_source = _load_tariff(tariff_csv, horizon_slots)

    baseline = _schedule(jobs, tariff, horizon_slots, "baseline")
    optimized = _schedule(jobs, tariff, horizon_slots, "optimized")
    for frame in (baseline, optimized):
        frame["energy_kwh"] = frame["energy_kwh"] * slot_hours
        frame["energy_cost"] = frame["energy_cost"] * slot_hours
    base_profile = _profile(baseline, tariff, horizon_slots, slot_hours)
    opt_profile = _profile(optimized, tariff, horizon_slots, slot_hours)
    base_summary = _summary(baseline, base_profile, horizon_slots, slot_hours)
    opt_summary = _summary(optimized, opt_profile, horizon_slots, slot_hours)

    def change(key: str) -> float | None:
        b, o = base_summary[key], opt_summary[key]
        if b is None or o is None:
            return None
        return float(o - b)

    def pct_change(key: str) -> float | None:
        b, o = base_summary[key], opt_summary[key]
        if b is None or o is None or b == 0:
            return None
        return float((o - b) / b * 100.0)

    outdir = Path(output_dir)
    outdir.mkdir(parents=True, exist_ok=True)
    baseline_path = outdir / "schedule_baseline.csv"
    optimized_path = outdir / "schedule_optimized.csv"
    profile_path = outdir / "schedule_slot_profiles.csv"
    jobs_path = outdir / "scenario_jobs.csv"
    tariff_path = outdir / "scenario_tariff.csv"
    summary_path = outdir / "scheduling_summary.json"

    jobs.to_csv(jobs_path, index=False)
    tariff.to_csv(tariff_path, index=False)
    baseline.to_csv(baseline_path, index=False)
    optimized.to_csv(optimized_path, index=False)
    profile = base_profile.merge(opt_profile, on=["slot", "price_per_kwh"], suffixes=("_baseline", "_optimized"))
    profile.to_csv(profile_path, index=False)

    summary = {
        "data_type": "SIMULATION_ONLY",
        "title": "ForgeFlex tariff-aware production scheduling comparison",
        "jobs_input_source": jobs_source,
        "tariff_input_source": tariff_source,
        "tariff_currency": "unspecified currency units per kWh",
        "baseline_method": "Per-machine earliest-due-date ordering; schedule each job at the earliest available contiguous slot at or after release, respecting its deadline when feasible.",
        "optimized_method": "Uses the same per-machine earliest-due-date ordering as the baseline; for each job, choose the lowest-tariff contiguous slot window that respects its release and deadline when feasible, with earliest-start tie-break. If no deadline-feasible window exists, use the cheapest available window and report the deadline miss.",
        "objective": "Minimize simulated tariff-weighted electricity cost subject to fixed job-to-machine assignments, non-overlap per machine, release times, and deadlines where feasible.",
        "assumptions": [
            "Job durations, machine assignments, power, release times, deadlines, and quantities are supplied or synthetically generated scenario inputs.",
            "Power is constant for each job throughout its scheduled duration.",
            "Jobs are non-preemptive and each machine runs at most one job at a time.",
            "Jobs on different machines may run concurrently; aggregate demand is the sum of their scheduled power.",
            "The default tariff is an illustrative synthetic time-of-use profile, not an actual utility tariff.",
            "No setup times, precedence constraints, labor constraints, machine failures, demand charges, or production-quality effects are modeled.",
            "No HIPE machine power measurements are used as job durations, production orders, or tariff data.",
        ],
        "limitations": [
            "The cost-aware method is a deterministic greedy heuristic, not a globally optimal mixed-integer schedule.",
            "This simulation does not establish real-factory energy savings, cost savings, feasibility, or ROI.",
            "A lower simulated bill does not necessarily imply lower energy consumption.",
        ],
        "parameters": {"seed": int(seed), "job_count_requested": int(job_count), "horizon_slots": int(horizon_slots), "slot_hours": float(slot_hours)},
        "baseline": base_summary,
        "optimized": opt_summary,
        "delta_optimized_minus_baseline": {
            "energy_kwh": change("total_energy_kwh"),
            "energy_cost": change("total_energy_cost"),
            "peak_aggregate_demand_kw": change("peak_aggregate_demand_kw"),
            "deadline_misses": change("deadline_misses_among_scheduled_jobs"),
        },
        "percent_change_optimized_vs_baseline": {
            "energy_kwh": pct_change("total_energy_kwh"),
            "energy_cost": pct_change("total_energy_cost"),
            "peak_aggregate_demand_kw": pct_change("peak_aggregate_demand_kw"),
        },
        "outputs": {
            "jobs_csv": str(jobs_path), "tariff_csv": str(tariff_path),
            "baseline_schedule_csv": str(baseline_path), "optimized_schedule_csv": str(optimized_path),
            "slot_profiles_csv": str(profile_path),
        },
    }
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return {"summary_json": str(summary_path), "summary": summary, **summary["outputs"]}
